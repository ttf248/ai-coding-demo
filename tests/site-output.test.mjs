test("reader escapes Markdown HTML and marks unavailable historical attachments", () => {
  const docs = documentOutputs(
    catalog,
    new Map([
      [
        "Readme.md",
        "# Example\n\n<script>alert(1)</script>\n\n[missing](nonexistent-history.zip)\n\n[guide](docs/react/Readme.md)\n\n```text\nline  \n\t \n```\n",
      ],
    ]),
  );
  const html = docs.get(readerPath("Readme.md"));
  assert.ok(html.includes("&lt;script&gt;alert(1)&lt;/script&gt;"));
  assert.ok(html.includes("文件未留存"));
  assert.ok(html.includes("原文路径：nonexistent-history.zip"));
  assert.ok(
    html.includes("readers/docs/react/Readme.html") ||
      html.includes('href="docs/react/Readme.html"'),
  );
  assert.ok(!html.includes('href="../../../nonexistent-history.zip"'));
  assert.ok(html.includes("line&#32;&#32;\n"));
  assert.ok(html.includes("&#9;&#32;\n"));
  assert.doesNotMatch(html, /[ \t]+$/m);
});
test("reader omits generator block markers but keeps fenced comments escaped", () => {
  const docs = documentOutputs(
    catalog,
    new Map([
      [
        "Readme.md",
        [
          "<!-- Generated by npm run generate. -->",
          "# Example",
          "",
          "<!-- archive:start -->",
          "",
          "## 当前归档信息（自动生成）",
          "",
          "- 实验 ID：`demo--run-r01`",
          "<!-- archive:end -->",
          "",
          "<!-- catalog:start -->",
          "<!-- catalog:end -->",
          "",
        ].join("\n"),
      ],
    ]),
  );
  const html = docs.get(readerPath("Readme.md"));
  assert.doesNotMatch(html, /&lt;!-- archive:(?:start|end) --&gt;/);
  assert.doesNotMatch(html, /&lt;!-- catalog:(?:start|end) --&gt;/);
  assert.doesNotMatch(html, /&lt;!-- Generated by npm run generate\. --&gt;/);
  assert.ok(html.includes("当前归档信息"));
  assert.ok(html.includes("demo--run-r01"));

  const fenced = documentOutputs(
    catalog,
    new Map([
      [
        "Readme.md",
        "```html\n<!-- archive:start -->\n```\n",
      ],
    ]),
  ).get(readerPath("Readme.md"));
  assert.ok(fenced.includes("&lt;!-- archive:start --&gt;"));
});
test("stripGeneratorMarkers only removes known markers outside code fences", () => {
  const source = [
    "<!-- archive:start -->",
    "kept",
    "<!-- archive:end -->",
    "```html",
    "<!-- archive:start -->",
    "```",
    "<!-- 普通注释 -->",
    "<!-- catalog:start -->",
  ].join("\n");
  const stripped = stripGeneratorMarkers(source);
  assert.ok(!stripped.includes("<!-- archive:start -->\nkept"));
  assert.ok(stripped.includes("kept"));
  assert.ok(stripped.includes("<!-- archive:start -->")); // fenced copy stays
  assert.ok(stripped.includes("<!-- 普通注释 -->")); // unknown comment stays
  assert.ok(!stripped.includes("<!-- catalog:start -->"));
});
