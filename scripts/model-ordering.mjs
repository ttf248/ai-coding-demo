import fs from "node:fs";
import vm from "node:vm";
import { pathToFileURL } from "node:url";

let modelUI;
export function compareModels(a, b) {
  if (!modelUI) {
    const context = {};
    vm.runInNewContext(
      fs.readFileSync(new URL("../assets/core.js", import.meta.url), "utf8"),
      context,
    );
    modelUI = context.ArchiveUI;
  }
  return modelUI.compareModels(a, b);
}

export function modelResearchQueue(models) {
  return {
    needsResearch: models
      .filter((model) => !model.ordering?.checkedAt)
      .map((model) => model.id),
    needsConfirmation: models
      .filter((model) =>
        ["partial", "unresolved"].includes(model.ordering?.status),
      )
      .map((model) => ({
        id: model.id,
        releaseDate: model.ordering.releaseDate,
        note: model.ordering.note,
      })),
  };
}

export function modelOrderingReport(models) {
  const sorted = [...models].sort(compareModels);
  const providers = [...new Set(sorted.map((model) => model.provider))];
  const statusLabels = {
    verified: "已核实",
    partial: "月份已确认，日待确认",
    unresolved: "待确认",
    "not-applicable": "不适用",
  };
  const cell = (value) => String(value ?? "未记录").replaceAll("|", "\\|");
  return (
    "<!-- Generated by npm run generate from catalog/models.json. Do not edit. -->\n" +
    "# 模型排序与官方资料核对表\n\n" +
    "排序依据保存在 [模型字典](../catalog/models.json)，筛选列表、主题页实验记录、按模型视图、档位矩阵及对比候选共用同一个排序函数。\n\n" +
    "1. 厂商分组保持现有顺序，厂商内部先按显式登记的代际从新到旧，再按同代能力层级从高到低，最后按发布日期从新到旧。\n" +
    "2. 代际由 generation 显式登记，不从显示名称解析。GPT-6.1 Sol 与 GPT-6 Astra / Sol / Luna 同属 GPT-6 代；Claude Opus / Sonnet / Haiku 5.5 同属 5.5 代。因此较晚发布的 Haiku 5.5 不会排在同代 Opus / Sonnet 前。能力优先级依据已保存的官方产品定位与比较作维护判断，不是跨代或跨厂商分数。\n" +
    "3. 日期缺失的型号置于该厂商末尾；同代能力缺失的型号置于能力已登记型号之后。其余并列保留版本、变体及 ID 的稳定顺序，不据此宣称能力强弱。\n" +
    "4. Free 等接入标签按可识别的基础模型首发排序，不将平台免费开放日期、文档修改、区域上线或正式版日期套用为历史检查点的首发日期。\n\n" +
    "`npm run models:pending` 仅列出缺少查证记录的新型号和已查过的待确认项，不联网。已有记录直接复用，包括明确登记的未知；仅新型号缺少记录或维护者明确要求重新查证时才查询官方消息。\n\n" +
    providers
      .map((provider) => {
        const items = sorted.filter((model) => model.provider === provider);
        return (
          `## ${provider || "未记录 / 多轮混合"}\n\n` +
          "| 顺序 | 模型 | 代际 | 同代能力优先级 | 发布日期 | 状态 | 查证日期 |\n|---|---|---|---|---|---|---|\n" +
          items
            .map((model, index) => {
              const order = model.ordering || {};
              return `| ${index + 1} | ${cell(model.label)} | ${order.generation?.join(".") || "未确认"} | ${order.capabilityRank ?? "未比较"} | ${cell(order.releaseDate)} | ${statusLabels[order.status] || "未查证"} | ${cell(order.checkedAt)} |`;
            })
            .join("\n") +
          "\n\n" +
          items
            .map((model) => {
              const order = model.ordering || {};
              const sources = (order.sources || [])
                .map((url, index) => `[官方来源 ${index + 1}](${url})`)
                .join(" · ");
              return `- **${cell(model.label)}**（\`${model.id}\`）：${order.note || "未查证。"} ${order.capabilityNote || ""}${sources ? " " + sources : ""}`;
            })
            .join("\n")
        );
      })
      .join("\n\n") +
    "\n"
  );
}

if (
  process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url
) {
  if (process.argv[2] !== "pending")
    throw Error("Usage: node scripts/model-ordering.mjs pending");
  const models = JSON.parse(
    fs.readFileSync(new URL("../catalog/models.json", import.meta.url), "utf8"),
  );
  console.log(JSON.stringify(modelResearchQueue(models), null, 2));
}
