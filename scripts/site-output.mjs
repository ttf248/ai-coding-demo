const escape = (value) =>
  String(value ?? "").replace(
    /[&<>"']/g,
    (c) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        c
      ],
  );
export const readerPath = (source) =>
  `assets/generated/readers/${source.replace(/\.md$/i, ".html")}`;

// 生成器写入 Markdown 的区块标记。标记必须留在 .md 文件里（replaceBlock 依赖它们），
// 但渲染时不能显示给读者，因此只在渲染前剔除这些整行。
const GENERATOR_MARKER =
  /^(?:<!-- (?:archive|catalog):(?:start|end) -->|<!-- Generated by npm run generate\b[^\n]*-->)$/;
export function stripGeneratorMarkers(text) {
  const kept = [];
  let fence = null;
  for (const line of String(text ?? "").split("\n")) {
    const fenceMatch = line.match(/^ {0,3}(`{3,}|~{3,})/);
    if (fenceMatch) {
      const marker = fenceMatch[1];
      if (!fence) fence = { char: marker[0], length: marker.length };
      else if (fence.char === marker[0] && marker.length >= fence.length)
        fence = null;
      kept.push(line);
      continue;
    }
    // 围栏内的内容原样保留：文档里存在合法的 HTML 注释示例。
    if (!fence && GENERATOR_MARKER.test(line.trim())) continue;
    kept.push(line);
  }
  return kept.join("\n");
}
export function screenshotMetadata(run) {
  if (!run.screenshot) return null;
  const bytes = fs.readFileSync(path.join(root, run.directory, run.screenshot));
  if (
    bytes.length < 24 ||
    !bytes.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))
  )
    throw Error(
      `Screenshot must be a valid PNG: ${run.directory}/${run.screenshot}`,
    );
  const digest = crypto.createHash("sha256").update(bytes).digest("hex");
  const width = bytes.readUInt32BE(16),
    height = bytes.readUInt32BE(20);
  return {
    width,
    height,
    hash: digest,
    capturedAt: run.screenshotCapturedAt || null,
    variants: [240, 480, 960]
      .filter((size) => size <= width)
      .map((size) => ({
        width: size,
        path: `assets/generated/screenshots/${run.id}/${digest.slice(0, 12)}-${size}.webp`,
      })),
    // 竖版整页截图在 16:10 封面里会缩成细条，另外派生一份顶部裁剪的封面图。
    // 原始 PNG 不被修改，完整长图仍在放大预览、查看原图与阅读页中呈现。
    // cover-v1 是配方版本号：裁剪参数变化时改版本号即可重新生成新文件。
    cover:
      height / width > 1.15
        ? [480, 960]
            .filter((size) => size <= width)
            .map((size) => ({
              width: size,
              height: Math.round((size * 10) / 16),
              path: `assets/generated/screenshots/${run.id}/${digest.slice(0, 12)}-cover-v1-${size}.webp`,
            }))
        : null,
  };
}
// 目录数据逐条输出：每条实验占一行，改动一条实验只产生一行 diff。
// 记录内部仍然紧凑，不做整体美化，体积与之前基本一致。
const ARCHIVE_COLLECTIONS = [
  "topics",
  "runs",
  "prompts",
  "models",
  "categories",
  "guides",
  "tools",
  "batches",
];
export function serializeArchive(summary) {
  const encode = (value) => JSON.stringify(value).replace(/</g, "\\u003c");
  const lines = ["window.ARCHIVE = {"];
  for (const [key, value] of Object.entries(summary)) {
    if (!ARCHIVE_COLLECTIONS.includes(key) || !Array.isArray(value)) {
      lines.push(encode(key) + ":" + encode(value) + ",");
      continue;
    }
    lines.push(encode(key) + ":[");
    for (const record of value) lines.push(encode(record) + ",");
    lines.push("],");
  }
  lines.push("};");
  return lines.join("\n");
}
export function browserOutputs(catalog) {
  const outputs = new Map();
  const json = (file, data) => outputs.set(file, JSON.stringify(data) + "\n");
  const runs = catalog.runs.map((run) => {
    const { raw, changes, billing, environment, input, score, ...summary } =
      run;
    const detailsHref = `assets/generated/topics/${run.topicId}.json`;
    const rawHref = `assets/generated/inputs/${run.rawHash}.json`;
    json(rawHref, raw);
    return {
      ...summary,
      score: {
        rubricVersion: score.rubricVersion,
        status: score.status,
        total: score.total,
        captureState: score.captureState,
        ...(score.status === "insufficient"
          ? { evidence: score.evidence }
          : {}),
      },
      reader: readerPath(run.document),
      hasRaw: !!raw.trim(),
      rawHref,
      detailsHref,
      input: {
        file: input.file,
        hash: input.hash,
        completeness: input.completeness,
        executionMode: input.executionMode || "unknown",
        ...(input.executionModeNote
          ? { executionModeNote: input.executionModeNote }
          : {}),
        authorization: input.authorization || "",
      },
      environment: {
        tool: environment.tool,
        toolId: environment.toolId,
        notes: "",
      },
    };
  });
  const prompts = catalog.prompts.map(({ text, ...prompt }) => {
    const textHref = `assets/generated/tasks/${prompt.hash}.json`;
    json(textHref, text);
    return { ...prompt, textHref };
  });
  for (const topic of catalog.topics)
    json(`assets/generated/topics/${topic.id}.json`, {
      runs: catalog.runs
        .filter((run) => run.topicId === topic.id)
        .map(({ raw, ...run }) => ({
          ...run,
          billing:
            run.billing?.type === "batch"
              ? { type: "batch", batchId: run.billing.batchId }
              : run.billing,
        })),
      prompts: prompts.filter((prompt) => prompt.topicId === topic.id),
    });
  const summary = {
    ...catalog,
    runs,
    prompts,
    guides: catalog.guides.map((guide) => ({
      ...guide,
      reader: readerPath(guide.document),
    })),
  };
  outputs.set(
    "assets/generated/catalog.js",
    "// Generated by npm run generate. Do not edit.\n" +
      serializeArchive(summary) +
      "\n",
  );
  return outputs;
}
export function documentOutputs(catalog, generated) {
  const MarkdownIt = require("markdown-it");
  const sourceFiles = [
    ...new Set([
      "Readme.md",
      ...catalog.runs.map((run) => run.document),
      ...catalog.topics.map((topic) => `${topic.directory}/Readme.md`),
      ...catalog.guides.map((guide) => guide.document),
      "docs/maintenance.md",
      "docs/model-ordering.md",
      "docs/case-scoring.md",
      "docs/scoring-reviews/2026-10-15-v2.md",
      "docs/archive-workspace.md",
      "docs/vercel-root-directories.md",
    ]),
  ].filter(
    (file) => generated.has(file) || fs.existsSync(path.join(root, file)),
  );
  const known = new Set(sourceFiles);
  const outputs = new Map();
  for (const source of sourceFiles) {
    const destination = readerPath(source);
    const relative = (file) =>
      path.posix.relative(path.posix.dirname(destination), file);
    const resolveLink = (href) => {
      if (/^(?:https?:|mailto:|data:|#)/i.test(href)) return href;
      const [local, fragment] = href.split("#");
      const [file, query] = local.split("?");
      const target = path.posix.normalize(
        path.posix.join(path.posix.dirname(source), file),
      );
      if (target.startsWith("../") || path.posix.isAbsolute(target)) return "#";
      if (!generated.has(target) && !fs.existsSync(path.join(root, target)))
        return null;
      return (
        relative(known.has(target) ? readerPath(target) : target) +
        (query ? "?" + query : "") +
        (fragment ? "#" + fragment : "")
      );
    };
    const md = new MarkdownIt({
      html: false,
      linkify: true,
      typographer: false,
    });
    md.linkify.set({ fuzzyEmail: false });
    const headings = [],
      used = new Map();
    const originalHeading = md.renderer.rules.heading_open;
    md.renderer.rules.heading_open = (tokens, index, options, env, self) => {
      const title = tokens[index + 1].content;
      const base =
        title
          .toLowerCase()
          .replace(/[^\p{L}\p{N}\s-]/gu, "")
          .trim()
          .replace(/\s+/g, "-") || "section";
      const count = used.get(base) || 0;
      used.set(base, count + 1);
      const id = base + (count ? "-" + count : "");
      tokens[index].attrSet("id", id);
      headings.push({ title, id, level: Number(tokens[index].tag.slice(1)) });
      return originalHeading
        ? originalHeading(tokens, index, options, env, self)
        : self.renderToken(tokens, index, options);
    };
    md.renderer.rules.link_open = (tokens, index, options, env, self) => {
      const original = tokens[index].attrGet("href"),
        href = resolveLink(original);
      if (href === null) {
        tokens[index].tag = "span";
        tokens[index].attrs = [
          ["class", "document-missing"],
          ["title", "原文路径：" + original],
        ];
        const closing = tokens
          .slice(index + 1)
          .find((token) => token.type === "link_close");
        if (closing) closing.tag = "span";
      } else tokens[index].attrSet("href", href);
      return self.renderToken(tokens, index, options);
    };
    md.renderer.rules.link_close = (tokens, index, options, env, self) =>
      (tokens[index].tag === "span" ? "<small>（文件未留存）</small>" : "") +
      self.renderToken(tokens, index, options);
    const originalImage = md.renderer.rules.image;
    md.renderer.rules.image = (tokens, index, options, env, self) => {
      tokens[index].attrSet("src", resolveLink(tokens[index].attrGet("src")));
      tokens[index].attrSet("loading", "lazy");
      return originalImage(tokens, index, options, env, self);
    };
    // Encode trailing whitespace without changing the displayed or copied text.
    const html = md
      .render(
        stripGeneratorMarkers(
          generated.get(source) ||
            fs.readFileSync(path.join(root, source), "utf8"),
        ),
      )
      .replace(/[ \t]+(?=\r?$)/gm, (whitespace) =>
        whitespace.replace(/ /g, "&#32;").replace(/\t/g, "&#9;"),
      );
    const run = catalog.runs.find((run) => run.document === source);
    const guide = catalog.guides.find((guide) => guide.document === source);
    const title =
      run?.title || guide?.title || headings[0]?.title || "项目文档";
    const description =
      run?.description ||
      (guide
        ? `${guide.title} 技术说明与可运行示例。`
        : "AI 编码实验档案与维护说明。");
    const toc = headings
      .filter((heading) => heading.level <= 3)
      .map(
        (heading) =>
          `<a class="toc-level-${heading.level}" href="#${escape(heading.id)}">${escape(heading.title)}</a>`,
      )
      .join("");
    const actions =
      `<a href="${escape(relative(source))}" download>下载 Markdown 原文 ↗</a>` +
      (run
        ? `<a href="${escape(relative("topic.html"))}?id=${escape(run.topicId)}#run-${escape(run.id)}">返回主题 →</a>` +
          (() => {
            const href =
              run.preview.kind === "external"
                ? run.preview.externalUrl
                : run.preview.pages?.find(
                    (page) => page.id === run.preview.defaultPage,
                  )?.href;
            return href
              ? `<a class="button primary" href="${escape(run.preview.kind === "external" ? href : relative(href))}" target="_blank" rel="noopener">运行作品 ↗</a>`
              : "";
          })() +
          `<a class="button" href="${escape(relative("compare.html"))}?left=${encodeURIComponent(run.id)}">对比此实验</a>`
        : "") +
      (guide
        ? `<a class="button primary" href="${escape(relative(guide.example))}">运行示例 ↗</a>`
        : "");
    const summaryRows = run
      ? [
          [
            "模型 / 档位",
            (catalog.models.find((model) => model.id === run.modelId)?.label ||
              run.modelId) +
              " · " +
              run.effort,
          ],
          [
            "任务版本 / 轮次",
            run.promptId +
              " · " +
              (run.runId.match(/r(\d+)$/)?.[1] || "未记录"),
          ],
          [
            "实验 / 归档日期",
            (run.date || "未记录") + " / " + (run.archivedAt || "未记录"),
          ],
          [
            "输入留存",
            {
              complete: "已记录原始输入",
              partial: "输入留存不完整",
              unknown: "输入留存未记录",
            }[run.input.completeness] || "未记录",
          ],
          [
            "执行模式",
            {
              strict: "按原任务执行",
              "design-enhanced": "自主设计授权",
              unknown: "执行模式未记录",
            }[run.input.executionMode || "unknown"],
          ],
          ["工具", run.environment.tool || "未记录"],
          [
            "截图评分",
            run.score.status === "rated"
              ? run.score.total + "/100 · 规则 v" + run.score.rubricVersion
              : {
                  insufficient: "证据不足",
                  unavailable: "无截图",
                  pending: "待评分",
                }[run.score.status] || "未记录",
          ],
          [
            "费用",
            run.billing?.type === "subscription"
              ? "订阅额度 · " + (run.billing.plan || "套餐未记录")
              : run.billing
                ? (run.billing.type === "batch"
                    ? "批次合计 · "
                    : "单次实验 · ") +
                  (run.billing.amount == null
                    ? "金额未记录"
                    : run.billing.amount + " " + (run.billing.unit || "")) +
                  (run.billing.type === "batch"
                    ? " · " +
                      (run.billing.caseCount ?? "未记录") +
                      " 个案例，不拆算单案例"
                    : "")
                : "费用未记录",
          ],
          [
            "耗时",
            run.billing?.duration
              ? (run.billing.type === "batch" ? "批次耗时 · " : "单次耗时 · ") +
                run.billing.duration.text +
                (run.billing.type === "batch"
                  ? " · " + (run.billing.caseCount ?? "未记录") + " 个案例"
                  : "")
              : "耗时未记录",
          ],
          [
            "人工修改",
            run.changes.length ? run.changes.join("；") : "未记录新增改动",
          ],
        ]
      : [];
    const summaryHTML = run
      ? `<section class="document-summary" aria-labelledby="record-summary-title"><h2 id="record-summary-title">实验摘要</h2><p>依据当前归档元数据整理；正文中的历史验证记录保留原有时间与口径。</p><dl>${summaryRows.map(([label, value]) => `<dt>${escape(label)}</dt><dd>${label === "人工修改" && run.changes.length ? `<details><summary>查看 ${run.changes.length} 条修改记录</summary>${escape(value)}</details>` : escape(value)}</dd>`).join("")}</dl><p><a href="${escape(relative(run.directory + "/" + run.input.file))}">查看完整原始输入 →</a></p></section>`
      : "";
    outputs.set(
      destination,
      `<!doctype html>\n<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="theme-color" content="#f6f7f9"><script src="${relative("assets/analytics.js")}" defer></script><title>${escape(title)} · AI Coding Demo</title><meta name="description" content="${escape(description)}"><meta property="og:title" content="${escape(title)}"><meta property="og:description" content="${escape(description)}"><meta property="og:type" content="article"><link rel="stylesheet" href="${relative("assets/site.css")}"><link rel="stylesheet" href="${relative("assets/document.css")}"><script src="${relative("assets/document.js")}" defer></script></head><body class="document-page"><a class="skip-link" href="#document-content">跳到正文</a><header class="site-header"><div class="container header-inner"><a class="brand" href="${relative("index.html")}"><span class="brand-mark">AI</span>CODING / DEMO</a><nav aria-label="主导航"><a href="${relative("index.html")}#projects">实验目录</a><a href="${relative("compare.html")}">模型对比</a><a href="${relative("index.html")}#guides">技术索引</a></nav></div></header><main class="container document-layout"><aside class="document-sidebar" id="document-toc"><details open><summary>本页目录</summary><nav aria-label="文档目录">${toc}</nav></details></aside><div><div class="document-actions">${actions}</div>${summaryHTML}<article id="document-content" class="document-content">${html}</article><p class="document-copy-status" role="status"></p><a class="document-toc-return" href="#document-toc">本页目录 ↑</a></div></main><footer><div class="container">AI CODING DEMO / 实验记录与技术说明。</div></footer></body></html>\n`,
    );
  }
  return outputs;
}
